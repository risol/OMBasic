#define OM_SYSTEM_MESSAGE_NAME_FILE_WRITE "File_Write"
#define OM_SYSTEM_MESSAGE_NAME_FILE_WRITE_COMPLETED "File_Write_Completed"
#define OM_SYSTEM_MESSAGE_NAME_TIMER_AFTER "Timer_After"

#endif
